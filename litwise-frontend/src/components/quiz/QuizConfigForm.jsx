'use client';

import React, { useState, useMemo } from 'react';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { Slider } from '@/components/ui/slider';
import { Badge } from '@/components/ui/badge';
import { Loader2, Sparkles, BookOpen } from 'lucide-react';
import { useGenerateQuiz } from '@/lib/react-query';

/**
 * Quiz Configuration Form Component
 * Allows user to customize quiz generation parameters
 * 
 * Features:
 * - Document selector (pre-selected if coming from paper view)
 * - Question count slider (5-50)
 * - Difficulty dropdown (Easy, Medium, Hard)
 * - Quiz type selector (Fact-based, Scenario-based, Mixed)
 * - Visual feedback and loading state
 */
export default function QuizConfigForm({ 
    paperId, 
    paperTitle, 
    onQuizGenerated,
    availablePapers = [],
}) {
    // Form state
    const [selectedPaperId, setSelectedPaperId] = useState(paperId || '');
    const [title, setTitle] = useState('');
    const [description, setDescription] = useState('');
    const [questionCount, setQuestionCount] = useState([10]); // Using array for Slider
    const [difficulty, setDifficulty] = useState('medium');
    const [quizType, setQuizType] = useState('mixed');

    // Mutation hook
    const generateQuizMutation = useGenerateQuiz();
    const isLoading = generateQuizMutation.isPending;

    // Auto-generate title based on topic
    const autoGeneratedTitle = useMemo(() => {
        if (!title && selectedPaperId && paperTitle) {
            return `${paperTitle} - Quiz`;
        }
        return title;
    }, [title, selectedPaperId, paperTitle]);

    // Validate form
    const isFormValid = useMemo(() => {
        return selectedPaperId && autoGeneratedTitle && questionCount[0] > 0;
    }, [selectedPaperId, autoGeneratedTitle, questionCount]);

    // Handle form submission
    const handleSubmit = (e) => {
        e.preventDefault();
        
        if (!isFormValid) return;

        const config = {
            title: autoGeneratedTitle,
            description: description || `Quiz on ${paperTitle}`,
            difficulty_level: difficulty,
            topic: autoGeneratedTitle,
            question_count: questionCount[0],
            quiz_type: quizType,
        };

        generateQuizMutation.mutate(
            { paperId: selectedPaperId, config },
            {
                onSuccess: (data) => {
                    // Call callback with generated quiz
                    onQuizGenerated?.(data);
                    
                    // Reset form
                    setTitle('');
                    setDescription('');
                    setQuestionCount([10]);
                    setDifficulty('medium');
                    setQuizType('mixed');
                },
            }
        );
    };

    return (
        <Card className="w-full max-w-2xl mx-auto shadow-lg border-0 bg-linear-to-br from-slate-50 to-slate-100 dark:from-slate-900 dark:to-slate-800">
            <CardHeader>
                <CardTitle className="flex items-center gap-2">
                    <Sparkles className="w-6 h-6 text-blue-500" />
                    Generate Quiz
                </CardTitle>
                <CardDescription>
                    Configure your quiz parameters to generate an interactive assessment
                </CardDescription>
            </CardHeader>

            <CardContent>
                <form onSubmit={handleSubmit} className="space-y-6">
                    {/* Paper Selection */}
                    {!paperId && (
                        <div className="space-y-2">
                            <Label htmlFor="paper">Select Document</Label>
                            <Select value={selectedPaperId} onValueChange={setSelectedPaperId}>
                                <SelectTrigger id="paper" className="bg-white">
                                    <SelectValue placeholder="Choose a document..." />
                                </SelectTrigger>
                                <SelectContent>
                                    {availablePapers.map(paper => (
                                        <SelectItem key={paper.id} value={paper.id}>
                                            {paper.title}
                                        </SelectItem>
                                    ))}
                                </SelectContent>
                            </Select>
                        </div>
                    )}

                    {/* Quiz Title */}
                    <div className="space-y-2">
                        <Label htmlFor="title">Quiz Title</Label>
                        <Input
                            id="title"
                            placeholder={autoGeneratedTitle || 'Enter quiz title...'}
                            value={title}
                            onChange={(e) => setTitle(e.target.value)}
                            className="bg-white"
                        />
                        {autoGeneratedTitle && !title && (
                            <p className="text-xs text-gray-500">
                                Auto-generated: {autoGeneratedTitle}
                            </p>
                        )}
                    </div>

                    {/* Quiz Description */}
                    <div className="space-y-2">
                        <Label htmlFor="description">Description (Optional)</Label>
                        <Input
                            id="description"
                            placeholder="Add a description for this quiz..."
                            value={description}
                            onChange={(e) => setDescription(e.target.value)}
                            className="bg-white"
                        />
                    </div>

                    {/* Question Count Slider */}
                    <div className="space-y-3">
                        <div className="flex justify-between items-center">
                            <Label>Number of Questions</Label>
                            <Badge variant="secondary" className="text-base px-3 py-1">
                                {questionCount[0]} questions
                            </Badge>
                        </div>
                        <Slider
                            value={questionCount}
                            onValueChange={setQuestionCount}
                            min={5}
                            max={50}
                            step={1}
                            className="w-full"
                        />
                        <div className="flex justify-between text-xs text-gray-500">
                            <span>5 questions</span>
                            <span>50 questions</span>
                        </div>
                    </div>

                    {/* Difficulty Level */}
                    <div className="space-y-2">
                        <Label htmlFor="difficulty">Difficulty Level</Label>
                        <Select value={difficulty} onValueChange={setDifficulty}>
                            <SelectTrigger id="difficulty" className="bg-white">
                                <SelectValue />
                            </SelectTrigger>
                            <SelectContent>
                                <SelectItem value="easy">
                                    Easy - Basic recall questions
                                </SelectItem>
                                <SelectItem value="medium">
                                    Medium - Application of concepts
                                </SelectItem>
                                <SelectItem value="hard">
                                    Hard - Synthesis and analysis
                                </SelectItem>
                            </SelectContent>
                        </Select>
                    </div>

                    {/* Quiz Type */}
                    <div className="space-y-2">
                        <Label htmlFor="quiz-type">Quiz Type</Label>
                        <Select value={quizType} onValueChange={setQuizType}>
                            <SelectTrigger id="quiz-type" className="bg-white">
                                <SelectValue />
                            </SelectTrigger>
                            <SelectContent>
                                <SelectItem value="fact_based">
                                    Fact-Based - Recall knowledge
                                </SelectItem>
                                <SelectItem value="scenario_based">
                                    Scenario-Based - Apply concepts
                                </SelectItem>
                                <SelectItem value="mixed">
                                    Mixed - Both types
                                </SelectItem>
                            </SelectContent>
                        </Select>
                    </div>

                    {/* Submit Button */}
                    <Button
                        type="submit"
                        disabled={!isFormValid || isLoading}
                        className="w-full bg-blue-600 hover:bg-blue-700 text-white py-2 h-11"
                    >
                        {isLoading ? (
                            <>
                                <Loader2 className="w-4 h-4 mr-2 animate-spin" />
                                Generating Quiz...
                            </>
                        ) : (
                            <>
                                <Sparkles className="w-4 h-4 mr-2" />
                                Generate Quiz
                            </>
                        )}
                    </Button>

                    {/* Error Display */}
                    {generateQuizMutation.isError && (
                        <div className="p-3 bg-red-50 border border-red-200 rounded-lg text-red-700 text-sm">
                            Error: {generateQuizMutation.error.message}
                        </div>
                    )}
                </form>
            </CardContent>
        </Card>
    );
}